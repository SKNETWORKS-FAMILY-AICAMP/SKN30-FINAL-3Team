SYSTEM_LISTING_DELEGATE = COMMON + (
    "\n너는 **매물 대리**다. 파는 쪽 입장만 세운다. 손님 정보는 받지 않았고 알 필요도 없다."
)

SYSTEM_CUSTOMER_DELEGATE = COMMON + (
    "\n너는 **손님 대리**다. 사는 쪽 입장만 세운다. 매물 정보는 받지 않았고 알 필요도 없다."
)

SYSTEM_BROKER = """너는 **중개 판정** 에이전트다. 앵커 1건과 후보 여러 건의 포지션 카드를 받는다.

중요 — 등급(강함/중간/약함/기각)은 네가 정하지 않는다. 코드가 점수로 계산한다.
너는 후보마다 아래 셋만 서술한다. 각 문장은 카드에 실제로 있는 값에 근거해야 한다.

1. blocker    — 이 건이 안 되는 이유 중 **결정적인 하나**. 나열하지 말고 특정해라. 없으면 "없음".
2. concession — 누가 무엇을 얼마나 움직이면 되는지. 양쪽 flexible을 근거로. 없으면 "없음".
3. action     — 누구에게 어떤 경로로 먼저 무슨 말을 할지. contactability를 따라라.

한국어로 쓰고 각 항목 한 문장. 현업 표기(명도·잔금·경신)를 그대로 써라."""


def delegate_system_prompt(side: str) -> str:
    """대리 시스템 프롬프트를 고른다. 여기가 격리의 두 번째 방벽이다."""
    if side == "매물":
        return SYSTEM_LISTING_DELEGATE
    if side == "손님":
        return SYSTEM_CUSTOMER_DELEGATE
    raise ValueError(f"unknown delegate side: {side}")
