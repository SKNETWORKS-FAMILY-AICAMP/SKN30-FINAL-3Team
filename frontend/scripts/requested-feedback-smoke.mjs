import { chromium } from "playwright";
import fs from "node:fs/promises";

const baseUrl = process.env.PROTOTYPE_URL || "http://127.0.0.1:4173/";
const outputDir = new URL("../artifacts/", import.meta.url);
await fs.mkdir(outputDir, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ permissions: ["clipboard-read", "clipboard-write"] });
const page = await context.newPage();
await page.setViewportSize({ width: 1600, height: 900 });
const consoleErrors = [];
const assertions = {};
const metrics = {};
page.on("console", (message) => { if (message.type() === "error") consoleErrors.push(message.text()); });
page.on("pageerror", (error) => consoleErrors.push(error.message));
await page.goto(baseUrl, { waitUntil: "networkidle" });
await page.locator(".ag-root-wrapper").waitFor({ state: "visible" });
const rowCheckboxes = page.getByRole("checkbox", { name: /Space 키로 행 선택 전환/ });
assertions.startsWithNoSelection = (await page.locator(".grid-statusbar").innerText()).includes("0건 선택");
await rowCheckboxes.nth(0).click();
await rowCheckboxes.nth(1).click();
await page.getByRole("button", { name: "전체 선택 해제" }).waitFor({ state: "visible" });
const filterBeforeClear = await page.locator(".filter-control select").first().inputValue();
await page.getByRole("button", { name: "전체 선택 해제" }).click();
await page.waitForTimeout(100);
assertions.explicitClearSelection = (await page.locator(".grid-statusbar").innerText()).includes("0건 선택");
assertions.clearPreservesFilter = (await page.locator(".filter-control select").first().inputValue()) === filterBeforeClear;
await rowCheckboxes.nth(0).click();
assertions.oneSelectedVoiceEntry = await page.getByRole("button", { name: "음성메모 입력", exact: true }).isEnabled();
await page.getByRole("button", { name: "전체 선택 해제" }).click();
await page.getByRole("button", { name: "음성메모 입력", exact: true }).click();
await page.locator(".detail-workspace-modal").waitFor({ state: "visible" });
await page.waitForTimeout(450);
const activeF2Text = await page.evaluate(() => document.activeElement?.textContent || "");
assertions.f2ProminentEntry = activeF2Text.includes("F2 · 상세 내부 기능") && await page.locator("#f2-panel").isVisible();
metrics.f2ScrollTop = await page.locator(".detail-workspace__content").evaluate((node) => node.scrollTop);
await page.locator(".detail-workspace__action-rail").getByRole("button", { name: "상세 닫기" }).click();
await page.getByRole("button", { name: "행 추가", exact: true }).click();
await page.getByRole("button", { name: "새 단지 추가", exact: true }).click();
await page.locator("#detail-new-complex-name").fill("검증 신규 단지");
await page.locator("#detail-new-complex-address").fill("서울 검증로 1");
await page.getByRole("button", { name: "추가 후 선택" }).click();
assertions.quickAddComplex = (await page.locator("#detail-complex").inputValue()) === "검증 신규 단지" && (await page.locator(".detail-complex-quick-add__status").innerText()).includes("추가하고 선택");
await page.locator(".detail-workspace__action-rail").getByRole("button", { name: "상세 닫기" }).click();
const dirtyDialog = page.getByRole("alertdialog");
await dirtyDialog.getByRole("button", { name: "저장 안 함", exact: true }).click();
for (let index = 0; index < 12; index += 1) await rowCheckboxes.nth(index).click();
await page.getByRole("button", { name: "문자 작업", exact: true }).click();
const composer = page.locator(".message-composer");
assertions.directMessageSource = (await composer.innerText()).includes("대상 출처 · 직접 선택");
const directRecipientDetails = composer.locator(".message-composer__details").first();
if ((await directRecipientDetails.getAttribute("open")) === null) await directRecipientDetails.locator("summary").click();
const directRecipientCheckboxes = composer.locator(".message-composer__recipients input[type=checkbox]");
assertions.directRecipientReview = (await directRecipientCheckboxes.count()) > 0;
if (assertions.directRecipientReview) {
  await directRecipientCheckboxes.first().uncheck();
  assertions.directRecipientReview = (await page.getByRole("button", { name: "번호 목록 복사" }).isDisabled());
  await directRecipientCheckboxes.first().check();
}
assertions.directCopyOnly = (await page.getByRole("dialog").getByRole("button").allTextContents()).every((text) => !["발송", "보내기", "전송", "지금 보내기"].includes(text.trim()));
await page.getByRole("button", { name: "닫기", exact: true }).last().click();
await page.getByRole("button", { name: "F3 캠페인" }).click();
await page.getByRole("heading", { name: "문자 캠페인 대상 판정" }).waitFor({ state: "visible" });
assertions.campaignSeparatePage = await page.locator('[data-screen-id="F3-PG-010"]').isVisible();
const metricText = await page.locator(".campaign-workspace__metrics").innerText();
assertions.campaignMetrics = ["F1 선택", "판정 대상", "제외", "연락처 없음", "동의 확인"].every((label) => metricText.includes(label));
assertions.campaignCanRun = await page.getByRole("button", { name: "선택 대상 판정" }).isEnabled();
if (assertions.campaignCanRun) {
  await page.getByRole("button", { name: "선택 대상 판정" }).click();
  await page.getByRole("button", { name: /F1 문자 작업으로 넘기기/ }).click();
  assertions.campaignMessageSource = (await composer.innerText()).includes("대상 출처 · F3 캠페인");
  await page.getByRole("button", { name: "닫기", exact: true }).last().click();
} else assertions.campaignMessageSource = false;
await page.getByRole("button", { name: "매물장으로 돌아가기" }).click();
await page.getByRole("button", { name: "F3 캠페인" }).click();
await page.getByRole("button", { name: "선택 대상 판정" }).click();
await page.screenshot({ path: new URL("16-requested-feedback-campaign.png", outputDir).pathname });
await browser.close();
const passed = Object.values(assertions).every(Boolean) && consoleErrors.length === 0;
const result = { baseUrl, assertions, metrics, consoleErrors, passed };
await fs.writeFile(new URL("requested-feedback-smoke.json", outputDir), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
if (!passed) process.exitCode = 1;
