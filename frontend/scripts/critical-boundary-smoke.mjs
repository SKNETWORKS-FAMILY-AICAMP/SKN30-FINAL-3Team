import { chromium } from "playwright";
import fs from "node:fs/promises";
const baseUrl=process.env.PROTOTYPE_URL || "http://127.0.0.1:4173/";
const browser=await chromium.launch({headless:true});
const context=await browser.newContext();
const page=await context.newPage({viewport:{width:1600,height:900}});
await page.addInitScript(() => { window.__lastPrototypeSavedRow = null; window.addEventListener("prototype:f1-row-saved", (event) => { window.__lastPrototypeSavedRow = event.detail; }); });
const consoleErrors=[];
page.on("console",m=>{if(m.type()==="error") consoleErrors.push(m.text())});
page.on("pageerror",e=>consoleErrors.push(e.message));
const a={};
await page.goto(baseUrl,{waitUntil:"networkidle"});
for (const unit of ["204", "206"]) {
  const jump = page.getByLabel("동·호 조회");
  await jump.fill(`101${unit}`);
  await page.getByRole("button", { name: "조회", exact: true }).click();
  await page.locator(".detail-workspace-modal").waitFor({ state: "visible" });
  a[`unit${unit}CleanOnOpen`] = (await page.getByText("모든 변경 저장됨", { exact: true }).count()) > 0;
  await page.locator(".detail-workspace__action-rail").getByRole("button", { name: "상세 닫기" }).click();
  await page.waitForTimeout(100);
  a[`unit${unit}ClosesWithoutDecision`] = (await page.getByRole("alertdialog").count()) === 0;
}
await page.getByRole("button",{name:/상세 열기/}).first().click();
const f2=page.locator(".detail-section--f2");
await f2.scrollIntoViewIfNeeded();
await f2.getByRole("button",{name:/상담 후 음성메모 녹음/}).click();
await f2.getByRole("button",{name:"녹음 종료",exact:true}).click();
await page.locator(".detail-workspace__action-rail").getByRole("button",{name:"상세 닫기"}).click();
const close=page.getByRole("alertdialog");
await close.waitFor({state:"visible"});
a.audioTriggersClosePolicy=await close.getByText("변경사항을 저장할까요?",{exact:true}).isVisible();
await close.getByRole("button",{name:"저장",exact:true}).click();
const savedF2Draft = await page.evaluate(() => window.__lastPrototypeSavedRow?.f2Draft);
await page.locator(".detail-workspace-modal").waitFor({state:"detached"});
a.audioRestoredAfterSave=Boolean(savedF2Draft?.audioSource && savedF2Draft?.state === "sourceReady");
await page.getByRole("button",{name:/래미안 원베일리 101동 203호 상세 열기/}).first().click();
await f2.scrollIntoViewIfNeeded();

const log=page.locator("#detail-log");
await log.scrollIntoViewIfNeeded();
await log.fill("주민번호 900101-1234567 확인");
await page.waitForTimeout(100);
await page.locator(".detail-workspace__action-rail").getByRole("button",{name:"저장",exact:true}).click();
const security=page.locator('[data-screen-id="F1-MOD-140"]');
await security.waitFor({state:"visible"});
a.securityGateVisible=await security.isVisible();
a.securityGateFocused=await page.evaluate(()=>document.activeElement?.closest?.('[data-screen-id="F1-MOD-140"]')!==null);

const gridLabel=await page.evaluate(()=>document.querySelector('[role="grid"]')?.getAttribute('aria-label'));
a.gridAriaLabel=gridLabel==="매물장 세대 그리드";
const result={assertions:a,gridLabel,consoleErrors,passed:Object.values(a).every(Boolean)&&consoleErrors.length===0};
await fs.writeFile(new URL('../artifacts/critical-boundary-smoke.json',import.meta.url),JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
await browser.close();
if(!result.passed) process.exitCode=1;
